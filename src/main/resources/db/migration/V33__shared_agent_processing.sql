CREATE TABLE agent_conversation_state (
  chat_guid VARCHAR(512) PRIMARY KEY,
  state_payload TEXT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE agent_inbound_messages (
  inbox_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_key VARCHAR(64) NOT NULL UNIQUE,
  chat_guid VARCHAR(512) NOT NULL,
  message_payload TEXT,
  start_payload TEXT,
  available_at TIMESTAMP WITH TIME ZONE NOT NULL,
  claimed_until TIMESTAMP WITH TIME ZONE,
  claim_token VARCHAR(36),
  completed_at TIMESTAMP WITH TIME ZONE,
  attempts INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE agent_inbound_chat_order (
  chat_guid VARCHAR(512) PRIMARY KEY
);

CREATE INDEX agent_inbound_messages_due ON agent_inbound_messages (completed_at, available_at, inbox_id);
CREATE INDEX agent_inbound_messages_chat ON agent_inbound_messages (chat_guid, completed_at, inbox_id);

CREATE TABLE agent_outbound_deliveries (
  delivery_id VARCHAR(36) PRIMARY KEY,
  outcome VARCHAR(16) NOT NULL,
  receipt TEXT,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  reservation_token VARCHAR(36),
  reserved_until TIMESTAMP WITH TIME ZONE,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX agent_outbound_deliveries_updated ON agent_outbound_deliveries (updated_at);
